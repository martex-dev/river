/**
 * The theme catalog (1.0.45). A theme is a palette inside a skin: four layered
 * surfaces (rail → sidebar → conversation → raised), text and two accents.
 * Everything else — hover, borders, muted text, gradients, readable ink on
 * buttons — is derived by the engine, so a new theme is one line here.
 */

export interface Theme {
  id: string;
  skin: string;
  name: string;
  mode: 'dark' | 'light';
  description: string;
  /** Rail and window frame (darkest in dark themes). */
  bg: string;
  /** Sidebars. */
  surface: string;
  /** The conversation. */
  base: string;
  /** Cards, inputs, popovers. */
  raised: string;
  text: string;
  accent: string;
  accent2: string;
}

type Row = [id: string, name: string, mode: 'dark' | 'light', colors: string, description: string];

function family(skin: string, rows: Row[]): Theme[] {
  return rows.map(([id, name, mode, colors, description]) => {
    const [bg, surface, base, raised, text, accent, accent2] = colors.split(' ') as [
      string,
      string,
      string,
      string,
      string,
      string,
      string,
    ];
    return {
      id: `${skin}-${id}`,
      skin,
      name,
      mode,
      description,
      bg,
      surface,
      base,
      raised,
      text,
      accent,
      accent2,
    };
  });
}

