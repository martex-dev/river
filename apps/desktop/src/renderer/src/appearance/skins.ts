/**
 * Skins (1.0.45): River's design languages. A skin decides the personality —
 * typography, geometry, materials, decoration, how messages are laid out — and
 * owns a family of themes (colours). Structure lives here as data; the few
 * decorations CSS can't express as tokens live in styles/skins.css under
 * html[data-decor="…"].
 */

export type UiFont = 'inter' | 'manrope' | 'plex' | 'exo' | 'grotesk' | 'hyperlegible' | 'mono';
export type DisplayFont = 'same' | 'orbitron' | 'playfair' | 'grotesk' | 'exo' | 'vt323' | 'plex';
export type MonoFont = 'jetbrains' | 'fira' | 'plex-mono' | 'vt323';
export type MessageStyle = 'flat' | 'bubbles' | 'cards' | 'terminal' | 'compact';
export type Pattern =
  'none' | 'grid' | 'dots' | 'lines' | 'scanlines' | 'noise' | 'stars' | 'blueprint' | 'waves';
export type Backdrop = 'solid' | 'gradient' | 'aurora' | 'mesh';
export type ButtonShape = 'pill' | 'rounded' | 'square' | 'cut';
export type AvatarShape = 'circle' | 'rounded' | 'square' | 'hexagon';
export type TabStyle = 'pill' | 'underline' | 'block';

export interface Skin {
  id: string;
  name: string;
  tagline: string;
  description: string;
  /** Expressive (A) or professional (B) — the theme browser groups by it. */
  direction: 'expressive' | 'professional';
  fonts: { ui: UiFont; display: DisplayFont; mono: MonoFont };
  /** Corner radius of panels and cards (px, before the person's radius setting). */
  radius: number;
  /** Corner radius of buttons and inputs (px). */
  control: number;
  buttons: ButtonShape;
  avatars: AvatarShape;
  borderWidth: number;
  /** 0–1: how much surfaces let the background through (with blur). */
  glass: number;
  blur: number;
  /** 0–1: luminous accents (active items, focus, speaking). */
  glow: number;
  shadow: 'none' | 'soft' | 'deep' | 'hard' | 'glow';
  /** 0–1: gradient strength on primary buttons and the backdrop. */
  gradient: number;
  pattern: Pattern;
  patternStrength: number;
  backdrop: Backdrop;
  headings: 'normal' | 'uppercase' | 'display';
  headingTracking: number;
  messageStyle: MessageStyle;
  tabs: TabStyle;
  /** Hook for skin-only decorations in skins.css. */
  decor: string;
  /** Spacing scale (1 = River's default). */
  spacing: number;
}

